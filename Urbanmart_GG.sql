/* Q- Find the average transaction value for each store. */    
    
SELECT s.store_name, AVG(t.total_amount) AS avg_transaction_value
FROM transactions t
JOIN stores s 
ON t.store_id = s.store_id
GROUP BY s.store_name;
    

/* Q- Based on stock-out and low-stock data, which store needs urgent replenishment, and what 
business risk does UrbanMart face if no action is taken?*/

SELECT s.store_name, SUM(CASE WHEN i.stock_quantity = 0 THEN 1 ELSE 0 END) AS stock_out_count,
SUM(CASE WHEN i.stock_quantity < 10 THEN 1 ELSE 0 END) AS low_stock_count
FROM inventory i
JOIN stores s 
ON i.store_id = s.store_id
GROUP BY s.store_name ; 

SELECT s.store_name, COUNT(*) AS urgent_items
FROM inventory i
JOIN stores s 
ON i.store_id = s.store_id
WHERE i.stock_quantity = 0 OR i.stock_quantity < 10
GROUP BY s.store_name
ORDER BY urgent_items DESC;

    
