-- Q8. Calculate total sales revenue generated by each store (store name + total revenue). 
    
SELECT s.store_name, SUM(t.total_amount) AS total_revenue
FROM transactions t
JOIN stores s  
ON t.store_id = s.store_id
GROUP BY s.store_name ;

-- Q9. Identify all products that are currently out of stock (quantity = 0) along with the store where they are missing. 

SELECT p.product_name, s.store_name, i.stock_quantity
FROM inventory i
JOIN products p 
ON i.product_id = p.product_id
JOIN stores s
ON i.store_id = s.store_id
WHERE i.stock_quantity = 0;
 
    
-- Q10. Find the top 5 best-selling products by total quantity sold.  
    
SELECT p.product_name, SUM(t.quantity) AS total_quantity_sold
FROM transactions t
JOIN products p 
ON t.product_id = p.product_id
GROUP BY p.product_name
ORDER BY total_quantity_sold DESC
LIMIT 5;

-- Q11. Show total sales made by each employee along with their store name. 

SELECT e.employee_name, s.store_name, SUM(t.total_amount) AS total_sales
FROM transactions t
JOIN employees e 
ON t.employee_id = e.employee_id
JOIN stores s
ON t.store_id = s.store_id
GROUP BY e.employee_name, s.store_name;

   
-- Q12. Display region-wise total revenue and number of transactions.

SELECT s.region, SUM(t.total_amount) AS total_revenue, COUNT(t.transaction_id) AS transaction_count
FROM transactions t
JOIN stores s 
ON t.store_id = s.store_id
GROUP BY s.region;


-- Q13. Find suppliers whose products have generated more than ₹50,000 in total sales.

SELECT s.supplier_name, SUM(t.total_amount) AS total_sales
FROM suppliers s
JOIN products p 
ON s.supplier_id = p.supplier_id
JOIN transactions t
ON p.product_id = t.product_id
GROUP BY s.supplier_name
HAVING SUM(t.total_amount) > 50000;
    
    
 /* Q-  List products where current stock is below 10 units (low-stock alert) with product and store 
names. */    
    
SELECT p.product_name, s.store_name, i.stock_quantity
FROM inventory i
JOIN products p 
ON i.product_id = p.product_id
JOIN stores s 
